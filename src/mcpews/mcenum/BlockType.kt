    override fun toString(): String {
        if (subName == "default") {
            return nameValue
        }

        return subName + " " + nameValue
    }

    companion object {
        private val fromName: HashMap<String, HashMap<Int, BlockType>> = HashMap()
        private val fromId: HashMap<Int, HashMap<Int, BlockType>> = HashMap()

        init {
            for (item in values()) {
                var itemMap = fromName[item.getName()]

                if (itemMap == null) {
                    itemMap = HashMap()
                    fromName[item.getName()] = itemMap
                    fromId[item.getId()] = itemMap
                }

                itemMap[item.getData()] = item
            }
        }

        @JvmStatic
        fun fromString(name: String): BlockType? = fromName[name]!![0]

        @JvmStatic
        fun fromString(name: String, data: Int): BlockType? = fromName[name]!![data]

        @JvmStatic
        fun fromId(id: Int): BlockType? = fromId[id]!![0]

        @JvmStatic
        fun fromId(id: Int, data: Int): BlockType? = fromId[id]!![data]
    }
