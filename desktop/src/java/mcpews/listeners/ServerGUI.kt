    private fun parseChatInput(input: String) {
        val currentParser = parser
        if (input.startsWith("/") && currentParser != null) { // Send command message
            val commandRequest = currentParser.parseCommand(input)

            if (commandRequest != null) {
                sendCommandToAll(commandRequest)
            }
        } else { // Send chat message
            sendMessageToAll(input)
        }
    }

    private fun sendCommandToAll(command: MCCommand) {
        val currentServer = server
        if (!isRunning || currentServer == null) {
            return
        }

        val con = currentServer.getClients()
        synchronized(con) {
            for (client in con) {
                client.send(this, command)
            }
        }
    }

    private fun sendMessageToAll(message: String) {
        val currentServer = server
        if (!isRunning || currentServer == null) {
            return
        }

        MCSocketServer.getLog().log(
            LogLevel.CHAT, "External: {0}",
            inputTextField.getText()
        )

        val cm: MCCommand = SayCommand(SayCommand.SayCommandInput(message))
        //MCSocketServer.messageLogger.log(LogLevel.DEBUG, cm.getMessage().getMessageText());
        val con = currentServer.getClients()
        synchronized(con) {
            for (client in con) {
                client.send(this, cm)
            }
        }
    }

