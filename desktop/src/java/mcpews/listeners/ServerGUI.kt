        private fun writeChatString(text: String) {
            val chatFormatting = SimpleAttributeSet()

            val tokens = text.split("\u00a7")
            for (token in tokens) {
                if (token.trim().isEmpty()) {
                    continue
                }

                if (getChatFormat(chatFormatting, token[0])) {
                    append(token.substring(1), chatFormatting)
                } else {
                    append(token.substring(0), chatFormatting)
                }
            }
        }

        private fun append(text: String, attribute: SimpleAttributeSet) {
            document.insertString(document.length, text, attribute)
        }

        fun filterLevel(level: Level) {
            EventQueue.invokeLater {
                try {
                    document.remove(0, document.length)

                    for (record in records) {
                        if (level.intValue() == Level.ALL.intValue() ||
                            record.getLevel().intValue() == level.intValue()
                        ) {
                            writeRecord(record)
                        }
                    }
                } catch (ex: BadLocationException) {
                    Logger.getLogger(ServerGUI::class.java.name).log(Level.SEVERE, null, ex)
                }
            }
        }

        fun filter(filter: LogFilter) {
            EventQueue.invokeLater {
                try {
                    document.remove(0, document.length)

                    for (record in records) {
                        if (filter.logAll) {
                            writeRecord(record)
                        } else {
                            if (filter.logChat && record.getLevel().intValue() == LogLevel.CHAT.intValue()) {
                                writeRecord(record)
                            } else if (filter.logDebug && record.getLevel().intValue() == LogLevel.DEBUG.intValue()) {
                                writeRecord(record)
                            } else if (filter.logInfo && record.getLevel().intValue() == Level.INFO.intValue()) {
                                writeRecord(record)
                            } else if (filter.logWarnings &&
                                record.getLevel().intValue() == Level.WARNING.intValue()
                            ) {
                                writeRecord(record)
                            } else if (filter.logSevere &&
                                record.getLevel().intValue() == Level.SEVERE.intValue()
                            ) {
                                writeRecord(record)
                            }
                        }
                    }
                } catch (ex: BadLocationException) {
                    Logger.getLogger(ServerGUI::class.java.name).log(Level.SEVERE, null, ex)
                }
            }
        }

        override fun publish(record: LogRecord) {
            super.publish(record)
            flush()

            records.add(record)

            if (this@ServerGUI.filter.logAll) {
                writeRecord(record)
            } else {
                if (this@ServerGUI.filter.logChat && record.getLevel().intValue() == LogLevel.CHAT.intValue()) {
                    writeRecord(record)
                } else if (this@ServerGUI.filter.logDebug && record.getLevel().intValue() == LogLevel.DEBUG.intValue()) {
                    writeRecord(record)
                } else if (this@ServerGUI.filter.logInfo && record.getLevel().intValue() == Level.INFO.intValue()) {
                    writeRecord(record)
                } else if (this@ServerGUI.filter.logWarnings &&
                    record.getLevel().intValue() == Level.WARNING.intValue()
                ) {
                    writeRecord(record)
                } else if (this@ServerGUI.filter.logSevere &&
                    record.getLevel().intValue() == Level.SEVERE.intValue()
                ) {
                    writeRecord(record)
                }
            }
        }

        private fun writeRecord(record: LogRecord) {
            if (textPane != null) {
                /*
                 Throwable throwable = record.getThrown();

                 if (throwable != null) {
                 StringWriter stringwriter = new StringWriter();
                 throwable.printStackTrace(new PrintWriter(stringwriter));
                 stringwriter.toString();
                 }
                 */

                EventQueue.invokeLater {
                    StyleConstants.setBold(dateKeyword, false)
                    StyleConstants.setBold(levelKeyword, true)
                    StyleConstants.setBold(messageKeyword, false)

                    val level = record.getLevel()
                    when (level.name) {
                        "INFO" -> {
                            StyleConstants.setForeground(dateKeyword, Color.black)
                            StyleConstants.setForeground(levelKeyword, Color.blue)
                            StyleConstants.setForeground(messageKeyword, Color.black)
                        }

                        "WARNING" -> {
                            StyleConstants.setBold(messageKeyword, true)

                            StyleConstants.setForeground(levelKeyword, warningColor)
                            StyleConstants.setForeground(messageKeyword, warningColor)
                        }

                        "SEVERE" -> {
                            StyleConstants.setBold(messageKeyword, true)

                            StyleConstants.setForeground(levelKeyword, Color.red)
                            StyleConstants.setForeground(messageKeyword, Color.red)
                        }

                        "CHAT" -> {
                            StyleConstants.setForeground(dateKeyword, Color.black)
                            StyleConstants.setForeground(levelKeyword, DesktopColors.DARK_GREEN)
                            StyleConstants.setForeground(messageKeyword, Color.black)
                        }

                        "DEBUG" -> {
                            StyleConstants.setForeground(dateKeyword, Color.black)
                            StyleConstants.setForeground(levelKeyword, DesktopColors.DARK_PURPLE)
                            StyleConstants.setForeground(messageKeyword, Color.black)
                        }

                        // FINEST, FINER, FINE, CONFIG and every other level use the Java default case.
                        else -> {
                            StyleConstants.setForeground(dateKeyword, Color.black)
                            StyleConstants.setForeground(levelKeyword, Color.black)
                            StyleConstants.setForeground(messageKeyword, Color.black)
                        }
                    }

                    try {
                        append(dateFormat.format(record.getMillis()), dateKeyword)
                        append(
                            " [" + record.getLevel().getName().uppercase(Locale.getDefault()) + "]: ",
                            levelKeyword
                        )

                        if (level.name == "CHAT") {
                            writeChatString(formatter.formatMessage(record))
                        } else {
                            append(formatter.formatMessage(record), messageKeyword)
                        }
                        append("\n", messageKeyword)
                    } catch (e: Exception) {
                    }
                }
            }
        }
    }

    private inner class LogFilter {

        var logAll: Boolean = false
        var logDebug: Boolean = false
        var logChat: Boolean = true
        var logInfo: Boolean = true
        var logWarnings: Boolean = true
        var logSevere: Boolean = true

        fun shouldLogDebug(status: Boolean) {
            logDebug = status
        }

        fun shouldLogChat(status: Boolean) {
            logChat = status
        }

        fun shouldLogInfo(status: Boolean) {
            logInfo = status
        }

        fun shouldLogWarnings(status: Boolean) {
            logWarnings = status
        }

        fun shouldLogSevere(status: Boolean) {
            logSevere = status
        }

        fun shouldLogAll(status: Boolean) {
            logAll = status
        }
    }

