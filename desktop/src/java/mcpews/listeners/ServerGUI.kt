    private fun createServer() {
        if (isRunning) {
            messageLogger.log(Level.FINE, "Server is already running.")
            return
        }

        val host: String = if (useLocalHostCheckBox.isSelected()) {
            "localhost"
        } else {
            try {
                InetAddress.getLocalHost().getHostName()
            } catch (ex: UnknownHostException) {
                messageLogger.log(Level.SEVERE, null, ex)
                "localhost"
            }
        }

        val port = portSpinner.getValue() as Int

        val newServer = MCSocketServer(InetSocketAddress(host, port))
        server = newServer

        val t = Thread(newServer)
        t.start()

        try {
            initializeListeners(newServer)
        } catch (e: Exception) {
            stopServer()
            e.printStackTrace()
            return
        }

        isRunning = true
        parser = CommandParser(newServer)

        startButton.setEnabled(false)
        stopButton.setEnabled(true)
    }

    private fun stopServer() {
        if (!isRunning) {
            messageLogger.log(Level.FINE, "No servers are running.")
            return
        }

        val currentServer = server ?: return

        messageLogger.log(
            Level.INFO,
            "Stopping server: {0}:" + currentServer.getAddress().getPort(),
            arrayOf<Any>(currentServer.getAddress().getHostString())
        )
        val cm: MCCommand = SayCommand(SayCommand.SayCommandInput("\u00a7cPEWS server is shutting down..."))

        val con = currentServer.getClients()
        synchronized(con) {
            for (client in con) {
                client.send(this, cm)
                client.close()
            }
        }

        try {
            Thread.sleep(150)
        } catch (ex: InterruptedException) {
            //Logger.getLogger(ServerGUI.class.getName()).log(Level.SEVERE, null, ex);
        }

        try {
            currentServer.stop(1000)
        } catch (ex: InterruptedException) {
            messageLogger.log(Level.SEVERE, "Server was interrupted.", ex)
        }

        isRunning = false
        clientListModel.clear()

        startButton.setEnabled(true)
        stopButton.setEnabled(false)
    }

